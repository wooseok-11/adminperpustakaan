export interface SekolahConfig {
  nama: string;
  npsn: string;
  alamat: string;
  telepon: string;
  email: string;
  website: string;
  logo: string;
}

export interface PengaturanConfig {
  namaPerpus: string;
  masaPinjam: number;
  maxBukuPinjam: number;
  tarifDenda: number;
  prefixTrx: string;
  adminToken: string;
  prefixSiswa: string;
}

export interface AdministratorItem {
  id: string;
  nama: string;
  username: string;
  email: string;
  password?: string;
  role: string;
  foto?: string;
  createdAt?: string;
}

export interface SiswaItem {
  id: string;
  nama: string;
  nisn: string;
  kelas: string;
  alamat: string;
  email?: string;
  password?: string;
  passwordAutoGenerated?: boolean;
  registeredAt?: string;
}

export interface EksemplarItem {
  kode: string;
  status: 'Tersedia' | 'Dipinjam' | 'Rusak' | 'Hilang';
}

export interface BukuItem {
  id: string;
  isbn: string;
  judul: string;
  penulis: string;
  penerbit: string;
  tahun: string;
  kategori: string;
  rak: string;
  jumlah: number;
  tersedia: number;
  kondisi?: string;
  driveLink?: string;
  cover?: string;
  eksemplar?: EksemplarItem[];
}

export interface EbookItem {
  id: string;
  judul: string;
  penulis: string;
  kategori: string;
  tahun: string;
  thumbnail: string;
  driveLink: string;
  status?: string;
}

export interface PeminjamanItem {
  id: string;
  idSiswa: string;
  idBuku: string;
  kodeEksemplar?: string;
  tglPinjam: string;
  tglJatuhTempo: string;
  tglKembali?: string;
  status: 'Dipinjam' | 'Dikembalikan';
}

export interface DendaItem {
  id: string;
  idTrx: string;
  idSiswa: string;
  hariTerlambat: number;
  totalDenda: number;
  dibayar: number;
  sisa: number;
  status: 'Belum Lunas' | 'Lunas';
  tgl: string;
}

export interface DatabaseSchema {
  Sekolah: SekolahConfig;
  Pengaturan: PengaturanConfig;
  Administrator: AdministratorItem[];
  Siswa: SiswaItem[];
  Buku: BukuItem[];
  Ebook: EbookItem[];
  Peminjaman: PeminjamanItem[];
  Pengembalian?: unknown[];
  Denda: DendaItem[];
}

