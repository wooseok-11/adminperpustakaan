import * as XLSX from 'xlsx';
import { DatabaseSchema, SiswaItem, BukuItem } from '../types';
import {
  normalizeKelas,
  generateStudentPassword,
  generateNextStudentId,
  buildEksemplarList,
} from './storage';

function normalizeHeader(str: string): string {
  return String(str || '').toLowerCase().replace(/[^a-z0-9]/g, '');
}

function escapeRegex(str: string): string {
  return String(str || '').replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function headerMatchScore(columnHeader: string, searchKey: string): number {
  const col = String(columnHeader || '').trim();
  const key = String(searchKey || '').trim();
  if (!col || !key) return 0;

  const colLower = col.toLowerCase();
  const keyLower = key.toLowerCase();

  if (colLower === keyLower) return 100;
  if (normalizeHeader(col) === normalizeHeader(key)) return 85;

  const wbRegex = new RegExp(`(^|[^a-z0-9])${escapeRegex(keyLower)}([^a-z0-9]|$)`, 'i');
  if (wbRegex.test(colLower)) return 70;

  if (colLower.includes(keyLower)) return 45;
  return 0;
}

export function smartGetValue(row: Record<string, unknown>, keys: string[]): string {
  if (!row) return '';
  const rowKeys = Object.keys(row);
  if (rowKeys.length === 0) return '';

  let bestValue = '';
  let bestScore = -1;

  for (const key of keys) {
    for (const colKey of rowKeys) {
      const score = headerMatchScore(colKey, key);
      if (score <= 0 || score <= bestScore) continue;

      const val = row[colKey];
      if (val === undefined || val === null) continue;
      const strVal = String(val).trim();
      if (strVal === '') continue;

      bestScore = score;
      bestValue = strVal;
    }
    if (bestScore === 100) break;
  }
  return bestValue;
}

export async function parseExcelFile(file: File): Promise<Record<string, unknown>[]> {
  const data = await file.arrayBuffer();
  const workbook = XLSX.read(data, { type: 'array' });
  const firstSheetName = workbook.SheetNames[0];
  if (!firstSheetName) return [];
  const worksheet = workbook.Sheets[firstSheetName];
  return XLSX.utils.sheet_to_json<Record<string, unknown>>(worksheet, { defval: '' });
}

export function importSiswaFromRows(
  rows: Record<string, unknown>[],
  currentDb: DatabaseSchema
): { inserted: number; skipped: number; updatedDb: DatabaseSchema } {
  const newDb = JSON.parse(JSON.stringify(currentDb)) as DatabaseSchema;
  let inserted = 0;
  let skipped = 0;

  for (const row of rows) {
    const namaVal = smartGetValue(row, [
      'Nama Siswa', 'Nama Lengkap Siswa', 'Nama Lengkap', 'Nama Murid',
      'Nama Peserta Didik', 'Nama', 'Name', 'Full Name', 'Fullname'
    ]);
    const nisnVal = smartGetValue(row, [
      'NISN', 'Nomor Induk Siswa Nasional', 'Nomor Induk Siswa',
      'NIS', 'Nis Nasional', 'Student ID Number'
    ]);
    const alamatVal = smartGetValue(row, [
      'Alamat Siswa', 'Alamat Lengkap', 'Alamat Tinggal', 'Tempat Tinggal',
      'Alamat', 'Address', 'Domisili'
    ]);
    const kelasVal = normalizeKelas(smartGetValue(row, [
      'Kelas', 'Rombel', 'Rombongan Belajar', 'Tingkat',
      'Class', 'Grade', 'Level'
    ]));
    const idVal = smartGetValue(row, [
      'No Anggota Perpus', 'Nomor Anggota Perpustakaan', 'No Anggota',
      'Nomor Anggota', 'Kartu Perpus', 'No Kartu Perpus', 'ID Siswa',
      'Nomer Anggota', 'No. Anggota', 'ID', 'Kode Siswa'
    ]);

    if (!namaVal) {
      skipped++;
      continue;
    }

    const newId = idVal || generateNextStudentId(newDb, kelasVal || 'X');
    if (newDb.Siswa.some((s) => s.id === newId)) {
      skipped++;
      continue;
    }

    const newSiswa: SiswaItem = {
      id: newId,
      nama: namaVal,
      nisn: nisnVal || '-',
      alamat: alamatVal || '-',
      kelas: kelasVal || '-',
      password: generateStudentPassword(namaVal, nisnVal || ''),
      passwordAutoGenerated: true,
      registeredAt: new Date().toISOString(),
    };

    newDb.Siswa.push(newSiswa);
    inserted++;
  }

  return { inserted, skipped, updatedDb: newDb };
}

export function importBukuFromRows(
  rows: Record<string, unknown>[],
  currentDb: DatabaseSchema
): { inserted: number; skipped: number; updatedDb: DatabaseSchema } {
  const newDb = JSON.parse(JSON.stringify(currentDb)) as DatabaseSchema;
  let inserted = 0;
  let skipped = 0;

  for (const row of rows) {
    const judulVal = smartGetValue(row, ['Judul Buku', 'Judul', 'Title', 'Nama Buku', 'Judul_Buku']);
    if (!judulVal) {
      skipped++;
      continue;
    }

    const jumlahStok = parseInt(smartGetValue(row, ['Jumlah Eksemplar', 'Jumlah', 'Stok', 'Quantity', 'Eksemplar', 'Qty']), 10) || 1;
    const idBukuVal = smartGetValue(row, ['Kode Buku', 'ID Buku', 'Book ID', 'Nomor Buku', 'ID', 'Kode']);
    const isbnVal = smartGetValue(row, ['ISBN', 'Barcode', 'Kode ISBN', 'Isbn', 'No ISBN']);
    const penulisVal = smartGetValue(row, ['Penulis', 'Pengarang', 'Author', 'Writer']);
    const penerbitVal = smartGetValue(row, ['Penerbit', 'Publisher', 'Penerbitan']);
    const tahunVal = smartGetValue(row, ['Tahun Terbit', 'Tahun', 'Year', 'Thn']);
    const kategoriVal = smartGetValue(row, ['Kategori', 'Category', 'Genre', 'Jenis']);
    const rakVal = smartGetValue(row, ['Lokasi Rak', 'Rak', 'Shelf', 'Rack', 'Nomor Rak']);
    const driveVal = smartGetValue(row, ['Link Drive', 'URL Drive', 'E-Book', 'Ebook', 'Ebook Link', 'Drive', 'Google Drive']);

    const newId = idBukuVal || `BUK-2026-${String(newDb.Buku.length + 1).padStart(4, '0')}`;
    if (newDb.Buku.some((b) => b.id === newId)) {
      skipped++;
      continue;
    }

    const newBuku: BukuItem = {
      id: newId,
      isbn: isbnVal || '-',
      judul: judulVal,
      penulis: penulisVal || '-',
      penerbit: penerbitVal || '-',
      tahun: tahunVal || '2024',
      kategori: kategoriVal || 'Umum',
      rak: rakVal || 'R-01',
      jumlah: jumlahStok,
      tersedia: jumlahStok,
      kondisi: 'Baik',
      driveLink: driveVal || '',
      cover: '',
      eksemplar: buildEksemplarList(newId, jumlahStok),
    };

    newDb.Buku.push(newBuku);
    inserted++;

    if (newBuku.driveLink && newBuku.driveLink.startsWith('http')) {
      const ebId = `EBK-2026-${String(newDb.Ebook.length + 1).padStart(4, '0')}`;
      newDb.Ebook.push({
        id: ebId,
        judul: newBuku.judul,
        penulis: newBuku.penulis,
        kategori: newBuku.kategori,
        tahun: newBuku.tahun,
        thumbnail: '',
        driveLink: newBuku.driveLink,
        status: 'Tersedia',
      });
    }
  }

  return { inserted, skipped, updatedDb: newDb };
}

export function exportToExcel(data: Record<string, unknown>[], filename: string, sheetName: string): void {
  const ws = XLSX.utils.json_to_sheet(data);
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, sheetName);
  XLSX.writeFile(wb, `${filename}.xlsx`);
}
