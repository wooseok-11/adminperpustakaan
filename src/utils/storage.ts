// NORMALISASI KELAS (Angka -> Romawi)
// =========================================================================
export function toRoman(num: number): string {
  const map: [string, number][] = [
    ['X', 10], ['IX', 9], ['V', 5], ['IV', 4], ['I', 1]
  ];
  let result = '';
  let remaining = num;
  while (remaining >= 10) { result += 'X'; remaining -= 10; }
  for (const [rom, val] of map.slice(1)) {
    while (remaining >= val) { result += rom; remaining -= val; }
  }
  return result;
}

export function normalizeKelas(input: unknown): string {
  if (input === undefined || input === null) return '';
  const str = String(input).trim().toUpperCase();
  if (!str) return '';

  // 1. Sudah romawi (X, XI, XII, VII, VIII, IX)
  const romanStart = str.match(/^(XII|XI|IX|VIII|VII|X)\b/);
  if (romanStart) {
    return str.replace(/\s*-\s*/g, ' ').replace(/\s+/g, ' ').trim();
  }

  // 2. Diawali angka -> romawi
  const numMatch = str.match(/^(\d{1,2})/);
  if (numMatch) {
    const numInt = parseInt(numMatch[1], 10);
    const roman = toRoman(numInt);
    if (roman) {
      const rest = str
        .slice(numMatch[1].length)
        .replace(/^[\s\-_]+/, '')
        .replace(/\s*-\s*/g, ' ')
        .replace(/\s+/g, ' ')
        .trim();
      return rest ? `${roman} ${rest}`.trim() : roman;
    }
  }

  return str.replace(/\s+/g, ' ').replace(/\s*-\s*/g, ' ').trim();
}

export function getClassLevel(kelas: string): 'X' | 'XI' | 'XII' {
  const k = String(kelas || '').trim().toUpperCase();
  if (k.startsWith('XII')) return 'XII';
  if (k.startsWith('XI')) return 'XI';
  return 'X';
}

// Auto-generate password siswa: <4 digit terakhir NISN><2 huruf awal nama> (e.g. 4567An)
export function generateStudentPassword(nama: string, nisn: string): string {
  const cleanNisn = String(nisn || '').replace(/[^0-9]/g, '');
  const lastFour = cleanNisn.slice(-4).padStart(4, '0');
  const cleanName = String(nama || '').trim();
  const initial = cleanName
    .split(/\s+/)
    .map((w) => w.charAt(0))
    .join('')
    .substring(0, 2)
    .toLowerCase();
  const formattedInitial = initial.charAt(0).toUpperCase() + initial.slice(1).toLowerCase();
  if (!formattedInitial) return lastFour + 'Ab';
  return lastFour + formattedInitial;
}

// Auto-generate ID siswa per tingkat
export function generateNextStudentId(db: DatabaseSchema, kelas: string, prefix?: string): string {
  const p = (prefix || db.Pengaturan.prefixSiswa || 'SIP').toUpperCase();
  const lvl = getClassLevel(kelas);
  const existing = (db.Siswa || []).filter((s) => {
    const parts = String(s.id).split('-');
    return parts[0]?.toUpperCase() === p && parts[1] === lvl;
  });
  const nums = existing.map((s) => parseInt(s.id.split('-').pop() || '0', 10) || 0);
  const next = (nums.length ? Math.max(...nums) : 0) + 1;
  return `${p}-${lvl}-${String(next).padStart(3, '0')}`;
}

// Auto-generate ID buku
export function generateNextBookId(db: DatabaseSchema, prefix = 'BUK'): string {
  const p = String(prefix).toUpperCase().trim() || 'BUK';
  const existing = (db.Buku || []).filter((b) => {
    const id = String(b.id || '').toUpperCase();
    return id.startsWith(p);
  });
  const nums = existing.map((b) => {
    const m = String(b.id).match(/(\d{3,4})$/);
    return m ? parseInt(m[1], 10) : 0;
  });
  const next = (nums.length ? Math.max(...nums) : 0) + 1;
  return `${p}-2026-${String(next).padStart(4, '0')}`;
}

// Build eksemplar list
export function buildEksemplarList(kodeBuku: string, jumlah: number): EksemplarItem[] {
  const kode = String(kodeBuku || '').toUpperCase().trim();
  const jumlahInt = Math.max(1, parseInt(String(jumlah), 10) || 1);
  const list: EksemplarItem[] = [];
  for (let i = 1; i <= jumlahInt; i++) {
    const numStr = String(i).padStart(3, '0');
    list.push({
      kode: `${kode}-${numStr}`,
      status: 'Tersedia',
    });
  }
  return list;
}

export function findEksemplarByKode(db: DatabaseSchema, kode: string): { buku: BukuItem; eksemplar: EksemplarItem } | null {
  const up = String(kode || '').toUpperCase().trim();
  for (const b of db.Buku || []) {
    if (!b.eksemplar) continue;
    const found = b.eksemplar.find((e) => String(e.kode).toUpperCase() === up);
    if (found) return { buku: b, eksemplar: found };
  }
  return null;
}

export function findBukuByCode(db: DatabaseSchema, code: string): BukuItem | null {
  const up = String(code || '').replace(/[\r\n\t]/g, '').trim().toUpperCase();
  const cleanIsbn = up.replace(/[^0-9Xx]/g, '');

  // 1. Direct ID
  let found = (db.Buku || []).find((b) => String(b.id).toUpperCase() === up);
  if (found) return found;

  // 2. Eksemplar
  const ex = findEksemplarByKode(db, up);
  if (ex) return ex.buku;

  // 3. ISBN
  if (cleanIsbn.length >= 8) {
    found = (db.Buku || []).find((b) => b.isbn.replace(/[^0-9Xx]/g, '').toUpperCase() === cleanIsbn);
    if (found) return found;
  }
  return null;
}

export function findSiswaByCode(db: DatabaseSchema, code: string): SiswaItem | null {
  const up = String(code || '').replace(/[\r\n\t]/g, '').trim().toUpperCase();
  return (db.Siswa || []).find(
    (s) => String(s.id).toUpperCase() === up || String(s.nisn).toUpperCase() === up
  ) || null;
}

export function sanitizeDatabase(raw: Partial<DatabaseSchema> | null | undefined): DatabaseSchema {
  const base = raw ? { ...raw } : {};
  const result: DatabaseSchema = {
    Sekolah: base.Sekolah ? { ...defaultDB.Sekolah, ...base.Sekolah } : { ...defaultDB.Sekolah },
    Pengaturan: base.Pengaturan
      ? { ...defaultDB.Pengaturan, ...base.Pengaturan }
      : { ...defaultDB.Pengaturan },
    Administrator: Array.isArray(base.Administrator) && base.Administrator.length > 0
      ? base.Administrator
      : defaultDB.Administrator,
    Siswa: Array.isArray(base.Siswa) ? base.Siswa : [],
    Buku: Array.isArray(base.Buku) ? base.Buku : [],
    Ebook: Array.isArray(base.Ebook) ? base.Ebook : [],
    Peminjaman: Array.isArray(base.Peminjaman) ? base.Peminjaman : [],
    Pengembalian: Array.isArray(base.Pengembalian) ? base.Pengembalian : [],
    Denda: Array.isArray(base.Denda) ? base.Denda : [],
  };

  if (!result.Pengaturan.adminToken) result.Pengaturan.adminToken = 'ADMIN-SIP-2026';
  if (!result.Pengaturan.prefixSiswa) result.Pengaturan.prefixSiswa = 'SIP';

  // Ensure exemplars exist and are valid for all books
  result.Buku = result.Buku.map((b) => {
    const jumlah = Math.max(1, parseInt(String(b.jumlah), 10) || 1);
    const dipinjamCount = result.Peminjaman.filter(
      (p) => p.idBuku === b.id && p.status === 'Dipinjam'
    ).length;
    const tersedia = Math.max(0, jumlah - dipinjamCount);

    let exemplars = Array.isArray(b.eksemplar) && b.eksemplar.length > 0 ? [...b.eksemplar] : [];
    if (exemplars.length === 0) {
      exemplars = buildEksemplarList(b.id, jumlah);
    } else if (exemplars.length < jumlah) {
      for (let i = exemplars.length + 1; i <= jumlah; i++) {
        exemplars.push({
          kode: `${b.id}-${String(i).padStart(3, '0')}`,
          status: 'Tersedia',
        });
      }
    }

    // Set status of exemplars based on loan count
    for (let i = 0; i < exemplars.length; i++) {
      exemplars[i].status = i < dipinjamCount ? 'Dipinjam' : 'Tersedia';
    }

    return {
      ...b,
      jumlah,
      tersedia,
      eksemplar: exemplars,
    };
  });

  return result;
}

export function loadRepository(): DatabaseSchema {
  try {
    const data = localStorage.getItem(DB_KEY);
    const parsed = data ? JSON.parse(data) : JSON.parse(JSON.stringify(defaultDB));
    return sanitizeDatabase(parsed);
  } catch (e) {
    console.error('Gagal membaca LocalStorage, memuat defaultDB:', e);
    return JSON.parse(JSON.stringify(defaultDB));
  }
}

export function saveRepository(db: DatabaseSchema): void {
  try {
    localStorage.setItem(DB_KEY, JSON.stringify(db));
  } catch (e) {
    console.error('Gagal menyimpan LocalStorage:', e);
  }
}

